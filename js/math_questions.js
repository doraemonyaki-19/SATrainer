// Helper for concise MC authoring.
function mq(id, skill, difficulty, passage, prompt, choices, answer, rationales) {
  return { id, skill, difficulty, type: "mc", passage, prompt, choices, answer, rationales };
}
// Helper for student-produced response (grid-in).
function sq(id, skill, difficulty, passage, prompt, answer, accept, explanation) {
  return {
    id, skill, difficulty, type: "spr", passage, prompt,
    answer, accept: accept || [], explanation,
  };
}

